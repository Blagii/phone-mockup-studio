// Optional Playwright integration test, with the same environment options as browser-smoke.cjs.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
(async () => {
    const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: process.env.CHROMIUM_SERVERLESS ? require('@sparticuz/chromium').default.args : [] });
    try {
        const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, acceptDownloads: true, serviceWorkers: 'block' });
        const base = process.env.STUDIO_URL || 'http://localhost:8778';
        if (process.env.THREE_TEST_ROOT) await context.route('https://cdn.jsdelivr.net/npm/three@0.160.0/**', route => route.fulfill({ path: path.join(process.env.THREE_TEST_ROOT, route.request().url().split('three@0.160.0/')[1]), contentType: 'application/javascript' }));
        if (process.env.STUDIO_TEST_PIXEL_RATIO) await context.route(base + '/', async route => {
            let html = await fs.readFile(path.join(__dirname, '../index.html'), 'utf8');
            html = html.replaceAll('Math.min(window.devicePixelRatio, 2)', process.env.STUDIO_TEST_PIXEL_RATIO);
            await route.fulfill({ body: html, contentType: 'text/html' });
        });
        const page = await context.newPage(), errors = [];
        page.on('pageerror', error => { errors.push(error.message); console.log('PAGE ERROR', error.message); });
        await page.goto(base + '/');
        await page.waitForSelector('body.promo-mode');
        await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Model loaded'), null, { timeout: 90000 });
        assert.equal(await page.locator('.timeline-scene').count(), 5);
        assert.equal(await page.locator('.shot-card').count(), 10);
        assert.equal(await page.locator('#promo-upload').isVisible(), true);
        const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.click('#promo-upload')]);
        await chooser.setFiles(path.join(__dirname, '../default-screenshot.jpg'));
        await page.waitForFunction(() => document.querySelector('#promo-media').options.length > 1);
        console.log('PASS promo workspace and image import');
        const heroTitle = 'Moja aplikacija.\nTvoja nova ideja.';
        await page.locator('#promo-title').fill(heroTitle);
        await page.locator('#promo-subtitle').fill('Samo druga scena');
        await page.locator('#scene-text-options > summary').click();
        await page.selectOption('#scene-text-font','mono');
        await page.selectOption('#scene-text-align','left');
        await page.locator('#scene-text-scale').evaluate(el => { el.value='125'; el.dispatchEvent(new Event('input',{bubbles:true})); });
        await page.locator('#scene-text-y').fill('22.5');
        await page.locator('#panel').evaluate(el => { el.scrollTop=el.scrollHeight; });
        await page.locator('.timeline-scene').nth(0).click();
        assert.equal(await page.locator('#panel').evaluate(el=>el.scrollTop),0);
        assert.equal(await page.locator('#scene-text-font').inputValue(),'sans');
        assert.equal(await page.locator('#scene-text-scale').inputValue(),'100');
        await page.locator('#promo-title').fill('Samo prva scena');
        await page.locator('#promo-subtitle').fill('Drugačiji podnaslov');
        await page.selectOption('#scene-text-font','serif');
        await page.locator('.timeline-scene').nth(1).click();
        assert.equal(await page.locator('#promo-title').inputValue(),heroTitle);
        assert.equal(await page.locator('#promo-subtitle').inputValue(),'Samo druga scena');
        assert.equal(await page.locator('#scene-text-font').inputValue(),'mono');
        assert.equal(await page.locator('#scene-text-scale').inputValue(),'125');
        assert.equal(await page.locator('#scene-text-y').inputValue(),'22.5');
        await page.selectOption('#promo-scene-picker',await page.locator('.timeline-scene').nth(0).getAttribute('data-id'));
        assert.equal(await page.locator('#promo-title').inputValue(),'Samo prva scena');
        await page.locator('.timeline-scene').nth(1).click();
        console.log('PASS per-scene titles, subtitles, typography, selection and inspector scroll reset');
        await page.locator('#promo-advanced > summary').click();
        async function adjust(id, value) { await page.locator(id).evaluate((el, value) => { el.value=String(value); el.dispatchEvent(new Event('input',{bubbles:true})); },value); }
        await adjust('#image-x',35); await adjust('#image-y',-20); await adjust('#image-zoom',150); await adjust('#image-angle',18);
        await adjust('#f-bri',130); await adjust('#f-sat',75); await page.selectOption('#image-fit','contain');
        await page.locator('.timeline-scene').nth(0).click();
        assert.equal(await page.locator('#image-x').inputValue(),'0'); assert.equal(await page.locator('#image-zoom').inputValue(),'100');
        assert.equal(await page.locator('#f-bri').inputValue(),'100'); assert.equal(await page.locator('#image-fit').inputValue(),'cover');
        await adjust('#image-x',-25);
        await page.locator('.timeline-scene').nth(1).click();
        assert.equal(await page.locator('#image-x').inputValue(),'35'); assert.equal(await page.locator('#image-y').inputValue(),'-20');
        assert.equal(await page.locator('#image-zoom').inputValue(),'150'); assert.equal(await page.locator('#image-angle').inputValue(),'18');
        assert.equal(await page.locator('#f-bri').inputValue(),'130'); assert.equal(await page.locator('#f-sat').inputValue(),'75'); assert.equal(await page.locator('#image-fit').inputValue(),'contain');
        await page.click('#promo-duplicate'); await adjust('#image-x',-60); await page.click('#image-reset'); await page.click('#btn-filters-reset');
        assert.equal(await page.locator('#image-x').inputValue(),'0'); assert.equal(await page.locator('#f-bri').inputValue(),'100');
        await page.click('#promo-remove'); // selects the next scene; return to the original Hero.
        await page.locator('.timeline-scene').nth(1).click();
        assert.equal(await page.locator('#image-x').inputValue(),'35'); assert.equal(await page.locator('#f-bri').inputValue(),'130');
        console.log('PASS scene-local image position, zoom, rotation, fit, filters and independent duplicate/reset');
        if (process.env.STUDIO_SCREENSHOT) await page.screenshot({ path: process.env.STUDIO_SCREENSHOT });
        await page.click('[aria-label="Dodaj scenu: Slide in"]');
        assert.equal(await page.locator('.timeline-scene').count(), 6);
        await page.click('#promo-duplicate'); assert.equal(await page.locator('.timeline-scene').count(), 7);
        await page.click('#promo-move-left'); await page.click('#promo-remove'); assert.equal(await page.locator('.timeline-scene').count(), 6);
        console.log('PASS add, edit, duplicate, move and remove scenes');
        await page.click('#promo-play'); await page.waitForTimeout(500);
        assert.equal(await page.locator('#promo-play').getAttribute('aria-label'), 'Pauziraj promo');
        await page.click('#promo-play');
        await page.selectOption('#promo-ratio', 'square');
        assert.equal(await page.locator('#promo-canvas').evaluate(c => c.width === c.height), true);
        await page.selectOption('#promo-ratio', 'vertical');
        console.log('PASS playback and aspect ratio');
        const saved = page.waitForEvent('download'); await page.click('#promo-save');
        const projectDownload = await saved;
        const project = JSON.parse(await fs.readFile(await projectDownload.path(), 'utf8'));
        assert.equal(project.scenes.length, 6); assert.match(project.image, /^data:image/);
        assert.equal(project.scenes[1].screenAdjust.image.x,35); assert.equal(project.scenes[0].screenAdjust.image.x,-25);
        assert.equal(project.scenes[1].textStyle.scale,125); assert.equal(project.scenes[0].textStyle.font,'serif');
        // Load a short two-shot version, exercising validation and image restoration too.
        project.scenes = [project.scenes[1], project.scenes[0]].map(scene => ({ ...scene, duration: 1.5 }));
        const [projectChooser] = await Promise.all([page.waitForEvent('filechooser'), page.click('#promo-open')]);
        await projectChooser.setFiles({ name: 'promo.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(project)) });
        await page.waitForFunction(() => document.querySelectorAll('.timeline-scene').length === 2);
        console.log('PASS save and reopen project with image');
        const downloaded = page.waitForEvent('download', { timeout: 60000 });
        await page.click('#promo-export');
        const video = await downloaded;
        assert.equal(await video.failure(), null);
        assert.ok((await fs.stat(await video.path())).size > 1000);
        if (process.env.STUDIO_VIDEO) await video.saveAs(process.env.STUDIO_VIDEO);
        await page.waitForFunction(() => !document.querySelector('#promo-export').disabled);
        console.log('PASS composed promo video download');
        await page.click('#promo-export'); await page.click('#promo-cancel');
        await page.waitForFunction(() => !document.querySelector('#promo-export').disabled);
        assert.match(await page.locator('#promo-notice').textContent(), /otkazano/);
        console.log('PASS cancel video export');
        await page.click('#mode-quick'); assert.equal(await page.locator('#btn-import').isVisible(), true);
        assert.equal(await page.locator('#image-x').inputValue(),'0'); assert.equal(await page.locator('#f-bri').inputValue(),'100');
        await page.click('#mode-promo');
        assert.equal(await page.locator('.timeline-scene').count(), 2);
        await page.setViewportSize({ width: 390, height: 844 });
        await page.waitForTimeout(400);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
        assert.equal(await page.locator('#promo-upload').isVisible(), true);
        console.log('PASS quick editor, preserved project and mobile layout');
        assert.deepEqual(errors, []);
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
